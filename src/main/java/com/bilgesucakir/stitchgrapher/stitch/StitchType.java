package com.bilgesucakir.stitchgrapher.stitch;

/**
 * Enum representing different types of crochet stitches.
 * Each stitch type has specific properties that can be used for graphing and analysis.
 * Includes:
 * - Single Crochet (SC),
 * - Half Double Crochet (HDC),
 * - Double Crochet (DC),
 * - Half Treble Crochet (HTR),
 * - Triple Crochet (TR),
 * - Slip Stitch (SLST),
 * - Chain (CH).
 */
public enum StitchType {

    SC,
    HDC,
    DC,
    HTR,
    TR,
    SLST,
    CH
}
