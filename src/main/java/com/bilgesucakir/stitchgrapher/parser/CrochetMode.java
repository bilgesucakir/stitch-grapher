package com.bilgesucakir.stitchgrapher.parser;

/**
 * Enum representing the mode of crochet pattern, either circular or flat.
 * Circular: The pattern is worked in rounds, where each round is connected to the previous one, forming a continuous spiral.
 * Flat: The pattern is worked in rows, where each row is connected to the previous one, forming a flat piece of fabric.
 */
public enum CrochetMode {
    CIRCULAR,
    FLAT
}
